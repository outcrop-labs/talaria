/// ECMAScript `String(number)` — the shortest roundtrip digits, reformatted
/// from Rust's `{:e}` (JS prints plain decimal while the point sits in
/// 1..=21, exponent form with an explicit `+` otherwise; `-0` keeps its sign).
pub fn js_number(n: &serde_json::Number) -> String {
    let v = n.as_f64().unwrap_or(0.0);
    if v == 0.0 {
        return if v.is_sign_positive() {
            "0".into()
        } else {
            "-0".into()
        };
    }
    if v.is_nan() {
        return "NaN".into();
    }
    if v.is_infinite() {
        return if v > 0.0 { "Infinity" } else { "-Infinity" }.into();
    }
    let neg = v < 0.0;
    let e = format!("{:e}", v.abs());
    let (digits, exp) = e.split_once('e').unwrap();
    let exp: i32 = exp.parse().unwrap();
    let digits = digits.replace('.', "");
    let point = exp + 1; // digits before the decimal point
    let mut out = String::new();
    if neg {
        out.push('-');
    }
    let k = digits.len() as i32;
    // ECMAScript `Number::toString`: plain decimal only while the point sits
    // in (-6, 21]; outside that, exponent form with an explicit `+`.
    if k <= point && point <= 21 {
        out.push_str(&digits);
        for _ in 0..(point - k) {
            out.push('0');
        }
    } else if point > 0 && point <= 21 {
        out.push_str(&digits[..point as usize]);
        out.push('.');
        out.push_str(&digits[point as usize..]);
    } else if point <= 0 && point > -6 {
        out.push_str("0.");
        for _ in 0..(-point) {
            out.push('0');
        }
        out.push_str(&digits);
    } else {
        out.push_str(&digits[..1]);
        if k > 1 {
            out.push('.');
            out.push_str(&digits[1..]);
        }
        out.push('e');
        let e10 = point - 1;
        if e10 >= 0 {
            out.push('+');
        }
        out.push_str(&e10.to_string());
    }
    out
}

fn utf16(s: &str) -> usize {
    s.chars().map(char::len_utf16).sum()
}

fn string_to_u16s(s: &str) -> Vec<u16> {
    s.encode_utf16().collect()
}

fn u16s_to_string(v: &[u16]) -> String {
    String::from_utf16_lossy(v)
}

