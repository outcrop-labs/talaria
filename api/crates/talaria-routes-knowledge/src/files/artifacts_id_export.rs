// /api/artifacts/{id}/export?format=docx|xlsx. Download an artifact as an
// Office file.
//
// The twin of the Google export without Google: the same read gate, but no
// connected account, no network and nothing left behind — the bytes are built
// in process and answered as an attachment. A SHEET becomes a one-sheet
// .xlsx, every other text artifact a .docx of its markdown, and a FILE
// artifact has no document to render at all (its own bytes already download
// through /api/uploads/{id}).

use axum::extract::{Path, Query, State};
use axum::http::{HeaderMap, StatusCode, header};
use axum::response::Response;
use serde::Deserialize;

use talaria_agent_auth::{AgentSubject, agent_caller};
use talaria_api_facades::kb::perms::{ITEM_ARTIFACT, can_read, can_read_agent, list_editors};
use talaria_artifacts::{artifact_to_markdown, get_artifact, guarded, sheet_grid};
use talaria_error::{house_error, internal};
use talaria_office::{OfficeKind, grid_to_xlsx, markdown_to_docx};
use talaria_session::{require_user, who_of};
use talaria_state::AppState;

#[derive(Deserialize)]
pub struct ExportQuery {
    format: Option<String>,
}

/// The saved name's stem: a title is display text, and this is going into a
/// filesystem and a header. Path separators, quotes and the characters
/// Windows refuses are dropped rather than substituted (a name with a slash in
/// it is a name the user never meant), and the stem is clipped so stem +
/// extension stays inside 120 characters.
fn safe_stem(title: &str) -> String {
    let cleaned: String = title
        .chars()
        .filter(|c| {
            !c.is_control()
                && !matches!(
                    c,
                    '/' | '\\' | '"' | '\'' | ':' | '*' | '?' | '<' | '>' | '|'
                )
        })
        .collect();
    let stem: String = cleaned.trim().chars().take(115).collect();
    let stem = stem.trim().to_string();
    if stem.is_empty() {
        // An untitled artifact still downloads as something openable.
        return "artifact".into();
    }
    stem
}

/// The filename a browser saves, per RFC 6266. Both forms are sent on
/// purpose: the quoted-string stays ASCII (a title's accents and emoji become
/// `_` there, because a browser that only reads this form guesses the encoding
/// and guesses wrong), and `filename*` carries the real UTF-8 title for every
/// browser in service. Nothing that could break out of the header survives
/// safe_stem, so neither form needs escaping of its own.
fn content_disposition(filename: &str) -> String {
    let ascii: String = filename
        .chars()
        .map(|c| {
            if c.is_ascii_graphic() || c == ' ' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let mut encoded = String::new();
    for b in filename.as_bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_' | b'~') {
            encoded.push(*b as char);
        } else {
            encoded.push_str(&format!("%{b:02X}"));
        }
    }
    format!("attachment; filename=\"{ascii}\"; filename*=UTF-8''{encoded}")
}

/// The generated bytes as a download. Not serve_upload: these bytes have no
/// upload row behind them and no inline question to answer — an Office file is
/// never rendered in a browser — and the RFC 6266 pair above is the point.
/// `no-store` because the response body is somebody's private document and
/// the URL says nothing about which version of it.
fn office_download(bytes: Vec<u8>, mime: &str, filename: &str) -> Response {
    let mut res = Response::new(axum::body::Body::from(bytes));
    let headers = res.headers_mut();
    headers.insert(
        header::CONTENT_TYPE,
        header::HeaderValue::from_str(mime).expect("office mime is header-safe"),
    );
    headers.insert(
        header::CONTENT_DISPOSITION,
        header::HeaderValue::from_str(&content_disposition(filename))
            .expect("disposition is header-safe"),
    );
    headers.insert(
        header::CACHE_CONTROL,
        header::HeaderValue::from_static("private, no-store"),
    );
    headers.insert(
        header::HeaderName::from_static("x-content-type-options"),
        header::HeaderValue::from_static("nosniff"),
    );
    res
}

pub async fn get(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(id): Path<String>,
    Query(q): Query<ExportQuery>,
) -> Result<Response, Response> {
    if let Some(gate) = talaria_params::uuid_gate_404(&id) {
        return Ok(gate);
    }
    let format = q.format.unwrap_or_default();
    if format != "docx" && format != "xlsx" {
        return Ok(house_error(
            StatusCode::BAD_REQUEST,
            "format must be docx or xlsx",
        ));
    }
    let artifact = match get_artifact(&state.pg, &id).await {
        Ok(a) => a,
        Err(e) => return Ok(internal("[artifacts] read failed", e)),
    };
    let Some(artifact) = artifact else {
        return Ok(house_error(StatusCode::NOT_FOUND, "not found"));
    };
    let editors = match list_editors(&state.pg, ITEM_ARTIFACT, &artifact.id).await {
        Ok(e) => e,
        Err(e) => return Ok(internal("[artifacts] grants read failed", e)),
    };

    // The read gate the GET and the Google export share, owner arm included —
    // a personal assistant exports its owner's private artifacts the way it
    // reads them. No audit entry: downloading a document you may read is a
    // read, and the GET does not log one either.
    let agent = agent_caller(&state.pg, &headers).await?;
    if let Some(agent) = agent {
        let name = agent.model.clone();
        let owner =
            match talaria_users::assistant_owner_for(&state.pg, &AgentSubject::Caller(agent)).await
            {
                Ok(v) => v,
                Err(e) => return Ok(internal("[artifacts] owner resolve failed", e)),
            };
        let team_ids = match talaria_teams::team_ids_for_agent(&state.pg, &name).await {
            Ok(v) => v,
            Err(e) => return Ok(internal("[artifacts] team membership read failed", e)),
        };
        if !can_read_agent(
            &guarded(&artifact),
            &name,
            owner.as_deref(),
            &editors,
            &team_ids,
        ) {
            return Ok(house_error(StatusCode::FORBIDDEN, "forbidden"));
        }
    } else {
        let user = require_user(&state, &headers).await?;
        let team_ids = match talaria_teams::team_ids_for_user(&state.pg, &user.id).await {
            Ok(v) => v,
            Err(e) => return Ok(internal("[artifacts] team membership read failed", e)),
        };
        if !can_read(
            &guarded(&artifact),
            Some(&user.id),
            who_of(&user).as_deref(),
            &editors,
            &team_ids,
        ) {
            return Ok(house_error(StatusCode::FORBIDDEN, "forbidden"));
        }
    }

    // Which file an artifact can become is its KIND's answer, not the
    // caller's: a sheet is a grid and a document is prose, and a mismatch is
    // the client asking for a conversion nobody defined — 400, the same
    // reading the Google export's NotExportable takes.
    let (bytes, kind) = match (artifact.kind.as_str(), format.as_str()) {
        ("file", _) => {
            return Ok(house_error(
                StatusCode::BAD_REQUEST,
                "a file artifact has no document to export",
            ));
        }
        ("sheet", "xlsx") => {
            // A body that never was a grid (unstructured text, an older shape)
            // still exports — one row per line keeps what the user typed,
            // where an empty workbook would quietly throw it away.
            let grid = sheet_grid(&artifact.body).unwrap_or_else(|| {
                artifact
                    .body
                    .lines()
                    .map(|line| vec![line.to_string()])
                    .collect()
            });
            let title = artifact.title.clone();
            // Off the executor: building a workbook is CPU work on a request
            // thread shared with every other request.
            let bytes = tokio::task::spawn_blocking(move || grid_to_xlsx(&title, &grid))
                .await
                .map_err(|e| internal("[artifacts] export writer failed", e))?;
            (bytes, OfficeKind::Xlsx)
        }
        ("sheet", _) => {
            return Ok(house_error(
                StatusCode::BAD_REQUEST,
                "a sheet artifact exports as xlsx, not docx",
            ));
        }
        (_, "docx") => {
            let title = artifact.title.clone();
            let markdown = artifact_to_markdown(&artifact);
            let bytes = tokio::task::spawn_blocking(move || markdown_to_docx(&title, &markdown))
                .await
                .map_err(|e| internal("[artifacts] export writer failed", e))?;
            (bytes, OfficeKind::Docx)
        }
        (kind, _) => {
            return Ok(house_error(
                StatusCode::BAD_REQUEST,
                &format!("a {kind} artifact exports as docx, not xlsx"),
            ));
        }
    };
    // The mime and the extension are the KIND's, from the crate that wrote the
    // bytes — a response that labelled .xlsx bytes as a Word document is the
    // one mislabelling a browser cannot recover from.
    Ok(office_download(
        bytes,
        kind.mime(),
        &format!("{}.{}", safe_stem(&artifact.title), kind.extension()),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn safe_stem_keeps_a_name_a_name() {
        assert_eq!(safe_stem("Q3 plan"), "Q3 plan");
        assert_eq!(safe_stem("../../etc/passwd"), "....etcpasswd");
        assert_eq!(safe_stem("  a\"b\nc  "), "abc");
        assert_eq!(safe_stem("   "), "artifact");
        assert_eq!(safe_stem(&"x".repeat(400)).chars().count(), 115);
    }

    /// The ASCII form is what a header may carry; the starred form is what the
    /// user actually named the file.
    #[test]
    fn content_disposition_sends_both_forms() {
        assert_eq!(
            content_disposition("Résumé.docx"),
            "attachment; filename=\"R_sum_.docx\"; \
             filename*=UTF-8''R%C3%A9sum%C3%A9.docx"
        );
        assert_eq!(
            content_disposition("plan.xlsx"),
            "attachment; filename=\"plan.xlsx\"; filename*=UTF-8''plan.xlsx"
        );
    }
}
