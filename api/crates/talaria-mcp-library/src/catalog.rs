// The catalog MIRROR — the official MCP registry, copied into Postgres and
// searched there. The picker never waits on the registry again: a search is
// one indexed query against `mcp_library_entries`, the featured shelf is one
// more, and both answer in milliseconds whether the registry is up, slow, or
// throttling (it does all three — see the header of lib.rs).
//
// HOW IT FILLS. The scheduler job (`sync_once`, leased, every 30 minutes):
//   1. FULL WALK, once: cursor-paginates `/v0.1/servers?version=latest`,
//      upserting each page as it lands, cursor saved after every page so a
//      stall resumes where it stopped instead of starting over. Rows the walk
//      never touched are pruned when it completes — they left the registry.
//   2. INCREMENTAL, after: `updated_since=<the previous pass's start>`, which
//      the registry answers WITH deleted entries, so removals and new versions
//      both land as one short page or two.
//   3. PUBLISHERS the registry lacks: the featured shelf is editorial, and a
//      featured company without a registry entry is still resolved — through
//      its /.well-known/mcp.json, else the documented-endpoint map — and
//      stored as a 'well-known' or 'curated' row so it searches like the rest.
// State (cursor, the since-mark, the last error) lives in app_settings under
// `mcp_library_sync`; the rows carry `synced_at` for the prune.
//
// WHAT A ROW IS. `entry` is the picker's wire shape (a `LibraryServer`,
// serialized) — the read path hands it through untouched. The other columns
// are the ranking: `title`/`domain`/`registry_name`/`description` feed a
// weighted tsvector (generated by the table), `domains` is every hostname the
// entry is known by (namespace, website, endpoint) for brand matches and the
// featured join, `tier` and `kind` are the filters.
//
// LIVENESS. `live_state` / `live_checked_at` / `live_detail` are written by
// the liveness job (`liveness`): search sinks `dead` rows below everything
// and the default answer leaves them out (counting them, so the picker can
// offer "show N unreachable"); the featured shelf never shows one. A row the
// sync rewrites with a changed entry loses its `live_checked_at` — the job
// takes never-checked rows first, so the new endpoint is asked within a run.
//
// THE FEATURED LIST is the built-in `FEATURED_DOMAINS` merged with the
// operator's edits (`featured`): added domains, hidden built-ins, and
// stand-ins (source 'operator') that win over the registry and the
// documented map for their domain.
//
// THE FALLBACK. Until the first full walk completes, the mirror may be empty
// or partial; a search that finds nothing locally in that window asks the
// live library (the old path) instead, so a fresh install's first minutes
// still answer. Once the walk is done the mirror is the only answer — an
// empty local result IS "no servers match".

