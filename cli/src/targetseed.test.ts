// targetseed: what a seed copies (registry units, never a workspace crate's),
// when it refuses, and that it falls back to a cold build rather than a byte
// copy or a hard link.

import { describe, expect, test } from 'bun:test'
import { spawnSync } from 'node:child_process'
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { realCtx, type Ctx } from './ctx'
import { fakeCtx } from './testing'
import {
  SEED_MARKER,
  heldFlocks,
  lockPackages,
  procLocksDev,
  profileBusy,
  rankSources,
  seedSelection,
  seedTarget,
} from './targetseed'

const H1 = '0123456789abcdef'
const H2 = 'fedcba9876543210'
const H3 = 'aaaaaaaaaaaaaaaa'
const H4 = 'bbbbbbbbbbbbbbbb'

/** A Cargo.lock with one registry crate (itoa), one git crate (gitdep), one
 *  workspace crate (core-x), and a name that is both (dual). */
const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "core-x"
version = "0.1.0"
dependencies = [
 "itoa",
]

[[package]]
name = "dual"
version = "0.2.0"

[[package]]
name = "dual"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "gitdep"
version = "0.3.0"
source = "git+https://example.com/gitdep#abc"

[[package]]
name = "itoa"
version = "1.0.14"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "11"
`

describe('lockPackages', () => {
  test('splits registry and git entries from path ones', () => {
    const p = lockPackages(LOCK)
    expect([...p.path].sort()).toEqual(['core-x', 'dual'])
    expect([...p.registry].sort()).toEqual(['dual', 'gitdep', 'itoa'])
    expect(p.sourced.has('itoa 1.0.14 registry+https://github.com/rust-lang/crates.io-index')).toBe(true)
    expect(p.sourced.size).toBe(3)
  })
})

describe('seedSelection', () => {
  const listing = {
    fingerprint: [`itoa-${H1}`, `core-x-${H2}`, `dual-${H3}`, `gitdep-${H4}`, 'not-a-unit'],
    build: [`itoa-${H1}`, `core-x-${H2}`],
    deps: [
      `libitoa-${H1}.rlib`,
      `libitoa-${H1}.rmeta`,
      `itoa-${H1}.d`,
      `libcore_x-${H2}.rlib`,
      `core_x-${H2}`,
      `libdual-${H3}.rlib`,
      `libgitdep-${H4}.rlib`,
      'libstray.rlib',
    ],
  }
  const sel = seedSelection(listing, lockPackages(LOCK))

  test('copies registry and git units with their artifacts', () => {
    expect(sel.copy).toContain(`.fingerprint/itoa-${H1}`)
    expect(sel.copy).toContain(`build/itoa-${H1}`)
    expect(sel.copy).toContain(`deps/libitoa-${H1}.rlib`)
    expect(sel.copy).toContain(`deps/itoa-${H1}.d`)
    expect(sel.copy).toContain(`.fingerprint/gitdep-${H4}`)
    expect(sel.copy).toContain(`deps/libgitdep-${H4}.rlib`)
    expect(sel.units).toBe(2)
  })

  test('never copies a workspace crate: no fingerprint, no build dir, no artifact', () => {
    // The trap this module exists for: a workspace crate's unit hash is the
    // same in every worktree, so a copied artifact passes for this tree's own.
    expect(sel.copy.some((p) => p.includes(H2))).toBe(false)
    expect(sel.pathUnits).toBe(2)
  })

  test('a name that is a path package anywhere in the lock is left out', () => {
    expect(sel.copy.some((p) => p.includes(H3))).toBe(false)
  })

  test('a file no kept fingerprint vouches for never arrives', () => {
    expect(sel.copy).not.toContain('deps/libstray.rlib')
    expect(sel.copy.every((p) => /^(\.fingerprint|build|deps)\//.test(p))).toBe(true)
  })
})

describe('lock reading', () => {
  test('/proc/locks rows, holders and waiters', () => {
    const procLocks = [
      '1: FLOCK  ADVISORY  WRITE 3512 fc:00:621256963 0 EOF',
      '2: POSIX  ADVISORY  WRITE 12749 00:a0:774692461 0 EOF',
      '18: -> FLOCK  ADVISORY  WRITE 1651448 fc:00:3717426 0 EOF',
      '18:   -> FLOCK  ADVISORY  WRITE 1663372 fc:00:3717427 0 EOF',
    ].join('\n')
    const held = heldFlocks(procLocks)
    expect(held.has('fc:00:621256963')).toBe(true)
    expect(held.has('fc:00:3717426')).toBe(true)
    expect(held.has('fc:00:3717427')).toBe(true)
    expect(held.has('00:a0:774692461')).toBe(false) // POSIX locks are not cargo's
  })

  test('a device number in /proc/locks spelling', () => {
    expect(procLocksDev(64512)).toBe('fc:00') // dm-0, the dev host's root
    expect(procLocksDev(2049)).toBe('08:01') // sda1
  })

  test('busy when /proc/locks names one of its lock files; unknown without /proc/locks', () => {
    const dir = mkdtempSync(join(tmpdir(), 'talaria-seedtest-'))
    try {
      writeFileSync(join(dir, '.cargo-build-lock'), '')
      const st = statSync(join(dir, '.cargo-build-lock'))
      expect(profileBusy(dir, `1: FLOCK  ADVISORY  WRITE 1 ${procLocksDev(st.dev)}:${st.ino} 0 EOF\n`)).toBe(true)
      expect(profileBusy(dir, '')).toBe(false)
      expect(profileBusy(dir, null)).toBeNull()
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})

describe('rankSources', () => {
  test('most shared lock entries first, then the most recently built', () => {
    const ranked = rankSources([
      { checkout: '/a', overlap: 10, lastUsedMs: 5 },
      { checkout: '/b', overlap: 400, lastUsedMs: 1 },
      { checkout: '/c', overlap: 400, lastUsedMs: 9 },
    ])
    expect(ranked.map((c) => c.checkout)).toEqual(['/c', '/b', '/a'])
  })
})

/** A source checkout with a built api/target and a new checkout with only
 *  its Cargo.lock, under one temp dir. */
function plantCheckouts() {
  const dir = mkdtempSync(join(tmpdir(), 'talaria-seedtest-'))
  const from = join(dir, 'from')
  const to = join(dir, 'to')
  const prof = join(from, 'api/target/debug')
  for (const d of [`.fingerprint/itoa-${H1}`, `.fingerprint/core-x-${H2}`, `build/itoa-${H1}/out`, 'deps', 'incremental/core_x-x']) {
    mkdirSync(join(prof, d), { recursive: true })
  }
  writeFileSync(join(prof, `.fingerprint/itoa-${H1}/lib-itoa`), 'fp-itoa')
  writeFileSync(join(prof, `.fingerprint/core-x-${H2}/lib-core_x`), 'fp-core')
  writeFileSync(join(prof, `build/itoa-${H1}/out/gen.rs`), 'gen')
  writeFileSync(join(prof, `deps/libitoa-${H1}.rlib`), 'itoa rlib bytes')
  writeFileSync(join(prof, `deps/libcore_x-${H2}.rlib`), 'STALE core-x')
  writeFileSync(join(prof, 'libcore_x.rlib'), 'STALE uplifted')
  for (const f of ['.cargo-lock', '.cargo-build-lock', '.cargo-artifact-lock']) writeFileSync(join(prof, f), '')
  mkdirSync(join(to, 'api'), { recursive: true })
  writeFileSync(join(to, 'api/Cargo.lock'), LOCK)
  return { dir, from, to }
}

describe('seedTarget', () => {
  test('the copy runs under shared flocks on every lock file, from the source profile', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      const ctx = fakeCtx()
      const r = await seedTarget(ctx, from, to, 'api')
      expect(r.seeded).toBe(true)
      const copy = ctx.calls.find((c) => c.cmd === 'flock' && c.args.includes('xargs'))!
      const prof = join(from, 'api/target/debug')
      expect(copy.opts?.cwd).toBe(prof)
      for (const f of ['.cargo-lock', '.cargo-build-lock', '.cargo-artifact-lock']) {
        const i = copy.args.indexOf(join(prof, f))
        expect(i).toBeGreaterThan(0)
        expect(copy.args.slice(i - 4, i)).toEqual(['--shared', '--nonblock', '--conflict-exit-code', '75'])
      }
      expect(copy.args.slice(copy.args.indexOf('xargs'))).toEqual([
        'xargs', '-0', '-a', join(to, 'api/target/.seed-list'), 'cp', '-a', '--reflink=always', '--parents', '-t', join(to, 'api/target/debug'),
      ])
      // The probe is a reflink too: never a plain copy.
      expect(ctx.calls.some((c) => c.cmd === 'cp' && c.args[0] === '--reflink=always')).toBe(true)
      expect(JSON.parse(readFileSync(join(to, 'api/target', SEED_MARKER), 'utf8')).units).toBe(1)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test('no reflink: no copy, no half-made target — a cold build', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      const ctx = fakeCtx()
      ctx.plant(['cp', ['--reflink=always', join(from, `api/target/debug/deps/libitoa-${H1}.rlib`), join(to, 'api/target/.reflink-probe')]], new Error('Operation not supported'))
      const r = await seedTarget(ctx, from, to, 'api')
      expect(r.seeded).toBe(false)
      expect(r.seeded === false && r.why).toContain('cannot reflink')
      expect(existsSync(join(to, 'api/target'))).toBe(false)
      expect(ctx.calls.some((c) => c.cmd === 'flock' && c.args.includes('xargs'))).toBe(false)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test('a cargo that took the source lock first: the seed stands down', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      const fake = fakeCtx()
      // flock -n answers 75 when a cargo holds the lock exclusively.
      const busy = Object.assign(new Error('Command failed'), { code: 75 })
      const exec: Ctx['exec'] = async (cmd, args, opts) => {
        if (cmd === 'flock' && args.includes('xargs')) throw busy
        return fake.exec(cmd, args, opts)
      }
      const r = await seedTarget({ ...fake, exec }, from, to, 'api')
      expect(r.seeded === false && r.why).toContain('a cargo started building')
      expect(existsSync(join(to, 'api/target'))).toBe(false)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test('a target dir that cannot be made is a failed seed, never a throw or a half-made target', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      chmodSync(join(to, 'api'), 0o555)
      const r = await seedTarget(fakeCtx(), from, to, 'api')
      expect(r.seeded === false && r.failed).toBe(true)
      expect(existsSync(join(to, 'api/target'))).toBe(false)
    } finally {
      chmodSync(join(to, 'api'), 0o755)
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test('refuses a target that already exists, and a source with no build', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      mkdirSync(join(to, 'api/target'))
      const r1 = await seedTarget(fakeCtx(), from, to, 'api')
      expect(r1.seeded === false && r1.why).toContain('already exists')
      rmSync(join(to, 'api/target'), { recursive: true })
      const r2 = await seedTarget(fakeCtx(), to, from, 'api')
      expect(r2.seeded === false && r2.why).toContain('already exists')
      const r3 = await seedTarget(fakeCtx(), join(dir, 'nowhere'), to, 'api')
      expect(r3.seeded === false && r3.why).toContain('no build to seed from')
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  // The real commands, on whatever filesystem the temp dir is: a reflink
  // filesystem (XFS, Btrfs) gets exactly the registry unit; any other gets
  // nothing at all. Either way, nothing of the workspace crate arrives.
  const tools = ['flock', 'xargs', 'cp'].every((t) => spawnSync('sh', ['-c', `command -v ${t}`]).status === 0)
  test.skipIf(!tools)('for real: the registry unit or nothing, never the workspace crate', async () => {
    const { dir, from, to } = plantCheckouts()
    try {
      const r = await seedTarget(realCtx(), from, to, 'api')
      const prof = join(to, 'api/target/debug')
      if (r.seeded) {
        expect(readFileSync(join(prof, `deps/libitoa-${H1}.rlib`), 'utf8')).toBe('itoa rlib bytes')
        expect(readFileSync(join(prof, `.fingerprint/itoa-${H1}/lib-itoa`), 'utf8')).toBe('fp-itoa')
        expect(readFileSync(join(prof, `build/itoa-${H1}/out/gen.rs`), 'utf8')).toBe('gen')
        expect(readdirSync(join(prof, 'deps'))).toEqual([`libitoa-${H1}.rlib`])
        expect(readdirSync(join(prof, '.fingerprint'))).toEqual([`itoa-${H1}`])
        expect(existsSync(join(prof, 'incremental'))).toBe(false)
        expect(existsSync(join(prof, 'libcore_x.rlib'))).toBe(false)
        expect(existsSync(join(to, 'api/target/.seed-list'))).toBe(false)
        // Timestamps ride along (`cp -a`), so cargo orders registry units as
        // it did in the source.
        expect(statSync(join(prof, `deps/libitoa-${H1}.rlib`)).mtimeMs).toBe(statSync(join(from, `api/target/debug/deps/libitoa-${H1}.rlib`)).mtimeMs)
      } else {
        expect(r.why).toContain('cannot reflink')
        expect(existsSync(join(to, 'api/target'))).toBe(false)
      }
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
