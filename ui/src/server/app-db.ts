// Per-app Postgres: one compose project per installed app, spawned on
// first use / install and stopped on uninstall (its data is deleted only
// when the admin asks — talaria-apps `uninstall_app`). App data never shares
// Talaria's database — a runaway query, a filled disk, or a DROP TABLE in
// an app cannot touch the platform catalog. The store API is unchanged;
// only the process behind it is.
import { randomBytes } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, chmodSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { spawn } from 'node:child_process'
import postgres, { type Sql } from 'postgres'
import { getSetting, setSetting } from './audit'
import { open, seal, secretboxFailure } from './secretbox'
import { slugOk, appDataDir } from './app-build/paths'

export { appDataDir }

const PASSWORDS_KEY = 'app_db_passwords'
const DEFAULT_IMAGE = 'docker.io/library/postgres:16-alpine'

const pools = new Map<string, Sql>()

function instanceId(): string {
  return process.env.TALARIA_WORKTREE || process.env.TALARIA_DEVBOX || 'talaria'
}

export function appDbContainer(slug: string): string {
  return `talaria-appdb-${instanceId()}-${slug}`
}

/** Is this process the product image? Only the image says so
 *  (TALARIA_INSTALL=image, its Dockerfile ENV). There it shares a network
 *  with app DBs and dials them by container name. A checkout install runs the
 *  same server-entry.ts (TALARIA_RUNTIME=prod-server) on the host, where a
 *  container name does not resolve, so it dials the published loopback port
 *  like dev does. Counting prod-server as the image sent a checkout install's
 *  first store call to an unresolvable host and refused to enable the app. */
export function inImage(): boolean {
  return process.env.TALARIA_INSTALL === 'image'
}

/** Does this process dial app DBs by container name on a shared network,
 *  rather than on the loopback port the container publishes? In the image,
 *  and wherever TALARIA_APP_DB_NETWORK names the network: runningNetwork()
 *  attaches the DB there and composeYaml then publishes no port, so a
 *  loopback dial has nothing to reach. A devbox is the second case: its
 *  compose sets the variable to the box's own network
 *  (docker/devbox.compose.yml), because the app runs in a container there,
 *  and 127.0.0.1 is that container's loopback, where nothing the host
 *  publishes can be reached. */
export function dialsByName(): boolean {
  return inImage() || Boolean(process.env.TALARIA_APP_DB_NETWORK)
}

function composeFile(slug: string): string {
  return join(appDataDir(slug), 'docker-compose.yml')
}

function envFile(slug: string): string {
  return join(appDataDir(slug), 'db.env')
}

function dumpFile(slug: string): string {
  return join(appDataDir(slug), 'dump.sql')
}

/** Compose file for one app DB. Password lives in db.env (0600), never here.
 *
 *  With no network to join (dev and a checkout install, where the host dials
 *  the published loopback port), the DB runs on docker's default `bridge`.
 *  A compose file that names no network gets a `<project>_default` network
 *  made for it, and every app DB took one: a subnet each from the daemon's
 *  ~30 address pools, which parallel stacks had already run dry (follow-ups
 *  A8, R19). Nothing reaches an app DB over a docker network here: the host
 *  dials 127.0.0.1:<published port>, and everything else (backup, the api's
 *  uninstall, the restore below) uses `docker exec`. On the default bridge a
 *  container started without `--network` can reach the DB by its IP, where a
 *  project network would admit only the project's own; the DB still demands
 *  its generated password (db.env).
 *
 *  The service is named for its container, never `postgres`. Compose gives a
 *  service its name as a DNS alias on every network it joins, and on a named
 *  network (the image's `internal`, a devbox's own) `postgres` is the
 *  platform's database. As `postgres` there, a lookup of `postgres` answered
 *  with both, and the platform's own connections reached an app's database
 *  and failed its password. The container name is unique, so its alias is
 *  the name it is dialled by and nothing else. One made before this, and
 *  still running, is recreated by appSql (`postgresAliasNetworks`). */
export function composeYaml(opts: { image: string; container: string; network: string | null }): string {
  const lines = [
    '# Generated by Talaria — do not edit.',
    'services:',
    `  ${opts.container}:`,
    `    image: ${opts.image}`,
    `    container_name: ${opts.container}`,
    '    restart: unless-stopped',
    '    security_opt:',
    '      - no-new-privileges:true',
    '    env_file:',
    '      - db.env',
    '    volumes:',
    '      - ./pg:/var/lib/postgresql/data',
  ]
  if (opts.network) {
    lines.push(
      '    networks:',
      '      - appdb',
      'networks:',
      '  appdb:',
      '    external: true',
      `    name: ${opts.network}`,
      '',
    )
  } else {
    lines.push('    network_mode: bridge', '    ports:', '      - "127.0.0.1::5432"', '')
  }
  return lines.join('\n')
}

/** The network compose made for an app DB before composeYaml put it on the
 *  default bridge. */
export function legacyAppDbNetwork(container: string): string {
  return `${container}_default`
}

/** Give back the subnet of an app DB's old project network once its `up` has
 *  moved the DB to the default bridge. The cleanup sweep leaves a network
 *  alone while its project still has a container, so a live app DB would
 *  have held its old one for as long as the app stayed installed. Best
 *  effort and quiet: no such network is the usual case, and one any
 *  container still names (running or stopped) is kept. */
async function releaseLegacyNetwork(container: string): Promise<void> {
  const name = legacyAppDbNetwork(container)
  if (!(await docker(['network', 'inspect', '--format', '{{.Id}}', name], 15_000)).ok) return
  const ps = await docker(['ps', '-a', '--format', '{{.Networks}}'], 15_000)
  if (!ps.ok) return
  const named = ps.stdout.split('\n').some((line) => line.split(',').some((n) => n.trim() === name))
  if (named) return
  if ((await docker(['network', 'rm', name], 30_000)).ok) {
    console.log(`[app-db] removed ${name} — ${container} runs on the default bridge now`)
  }
}

function readPasswordFile(path: string): string | null {
  if (!existsSync(path)) return null
  const m = readFileSync(path, 'utf8').match(/^POSTGRES_PASSWORD=(.*)$/m)
  const pass = m?.[1]?.trim() ?? ''
  return pass || null
}

/** Write the app DB's db.env (0600). The app's data directory is created
 *  first (0700): a fresh app reaches this on its first store call, before
 *  spawnContainer has made the directory, and writing into a directory that
 *  does not exist failed that call with ENOENT. */
export function writeDbEnv(slug: string, password: string): void {
  mkdirSync(appDataDir(slug), { recursive: true, mode: 0o700 })
  const path = envFile(slug)
  writeFileSync(path, `POSTGRES_USER=talaria\nPOSTGRES_PASSWORD=${password}\nPOSTGRES_DB=talaria\n`, {
    mode: 0o600,
  })
  chmodSync(path, 0o600)
}

async function loadOrCreatePassword(slug: string): Promise<string> {
  const fail = secretboxFailure()
  if (fail) throw new Error(`app db password: ${fail}`)
  const fromFile = readPasswordFile(envFile(slug))
  const stored = await getSetting<Record<string, string>>(PASSWORDS_KEY, {})
  let pass = fromFile
  if (!pass && stored[slug]) {
    try {
      pass = open(stored[slug])
    } catch {
      pass = null
    }
  }
  if (!pass) pass = randomBytes(24).toString('base64url')
  let sealedOk = false
  if (stored[slug]) {
    try {
      sealedOk = open(stored[slug]) === pass
    } catch {
      sealedOk = false
    }
  }
  if (!sealedOk) {
    await setSetting(PASSWORDS_KEY, { ...stored, [slug]: seal(pass) })
  }
  writeDbEnv(slug, pass)
  return pass
}

async function docker(
  args: string[],
  timeoutMs = 60_000,
  stdin?: string,
): Promise<{ ok: boolean; stdout: string; stderr: string }> {
  const child = spawn('docker', args, { stdio: [stdin != null ? 'pipe' : 'ignore', 'pipe', 'pipe'] })
  let stdout = ''
  let stderr = ''
  child.stdout?.on('data', (c: Buffer) => {
    stdout += c.toString()
  })
  child.stderr?.on('data', (c: Buffer) => {
    stderr += c.toString()
  })
  return await new Promise((resolve) => {
    const t = setTimeout(() => {
      child.kill('SIGKILL')
      resolve({ ok: false, stdout, stderr: stderr || `docker ${args[0]} timed out` })
    }, timeoutMs)
    if (stdin != null) child.stdin?.end(stdin)
    child.on('close', (code) => {
      clearTimeout(t)
      resolve({ ok: code === 0, stdout: stdout.trim(), stderr: stderr.trim() })
    })
    child.on('error', (e) => {
      clearTimeout(t)
      resolve({ ok: false, stdout, stderr: e instanceof Error ? e.message : String(e) })
    })
  })
}


async function compose(slug: string, args: string[], timeoutMs = 120_000): Promise<{ ok: boolean; stdout: string; stderr: string }> {
  return docker(['compose', '-p', appDbContainer(slug), '-f', composeFile(slug), ...args], timeoutMs)
}

async function runningNetwork(): Promise<string | null> {
  const named = process.env.TALARIA_APP_DB_NETWORK
  if (named) return named
  // Inside the image the app is on `internal`; attach app DBs there so the
  // fleet network never sees postgres (compose.yml: agents can reach the app,
  // never postgres).
  const self = process.env.HOSTNAME
  if (!self || !inImage()) return null
  const inspect = await docker(['inspect', '-f', '{{range $k,$v := .NetworkSettings.Networks}}{{$k}}\n{{end}}', self])
  const nets = inspect.stdout.split('\n').map((s) => s.trim()).filter(Boolean)
  return nets.find((n) => n.endsWith('_internal') || n === 'internal') ?? nets[0] ?? null
}

async function pinnedImage(): Promise<string> {
  const tag = process.env.TALARIA_APP_DB_IMAGE || process.env.TALARIA_PG_IMAGE || DEFAULT_IMAGE
  const r = await docker(['image', 'inspect', '-f', '{{json .RepoDigests}}', tag], 15_000)
  if (r.ok) {
    try {
      const digests = JSON.parse(r.stdout) as unknown
      if (Array.isArray(digests) && typeof digests[0] === 'string' && digests[0]) return digests[0]
    } catch {
      /* tag fallback */
    }
  }
  return tag
}

async function containerState(name: string): Promise<'running' | 'exited' | 'missing'> {
  const r = await docker(['inspect', '-f', '{{.State.Running}}', name], 10_000)
  if (!r.ok) return 'missing'
  return r.stdout === 'true' ? 'running' : 'exited'
}

/** Ready over TCP, not the unix socket. A fresh cluster's entrypoint runs
 *  initdb under a temporary server that listens on the socket only, then
 *  restarts it: a socket check passed during that window, and the host's
 *  first TCP connection (the published port, or the container name) was
 *  reset — a fresh install's first build failed "database did not start:
 *  read ECONNRESET". The temporary server takes no TCP, so this waits it out. */
async function waitHealthy(name: string, timeoutMs = 60_000): Promise<boolean> {
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    const r = await docker(['exec', name, 'pg_isready', '-h', '127.0.0.1', '-U', 'talaria', '-d', 'talaria'], 8_000)
    if (r.ok) return true
    await new Promise<void>((resolve) => setTimeout(resolve, 400))
  }
  return false
}


type NetworkEndpoint = { Aliases?: string[] | null; DNSNames?: string[] | null } | null

/** The named networks on which a container answers to `postgres`: what an
 *  app DB made before composeYaml named its service for its container does,
 *  everywhere it joined a network. The default `bridge` has no DNS, so a
 *  name there answers nothing. Pure, over `{{json .NetworkSettings.Networks}}`. */
export function postgresAliasNetworks(networks: Record<string, NetworkEndpoint> | null): string[] {
  return Object.entries(networks ?? {})
    .filter(([net, ep]) => net !== 'bridge' && [...(ep?.Aliases ?? []), ...(ep?.DNSNames ?? [])].includes('postgres'))
    .map(([net]) => net)
}

async function answersAsPostgres(name: string): Promise<string[]> {
  const r = await docker(['inspect', '-f', '{{json .NetworkSettings.Networks}}', name], 10_000)
  if (!r.ok) return []
  try {
    return postgresAliasNetworks(JSON.parse(r.stdout) as Record<string, NetworkEndpoint> | null)
  } catch {
    return []
  }
}

/** Recreate this app's database under its own name if it runs answering to
 *  `postgres` on a network it shares with the platform (composeYaml). Reused
 *  as it was, it would go on answering for as long as it ran, and
 *  `restart: unless-stopped` keeps it running across reboots; meanwhile any
 *  of the platform's connections to `postgres` can land on it and fail its
 *  password. It reads nothing from the platform's database (the password is
 *  the one in db.env, which the running container was started with), so
 *  host boot runs it for every installed app before anything there is read
 *  (app-build/reconcile.ts), and the database is back up whether or not the
 *  app's build then passes. A stopped one answers nothing; spawnContainer
 *  replaces it. Its data is a bind mount and stays. Says whether it did. */
export async function recreateIfAliased(slug: string): Promise<boolean> {
  if (!slugOk(slug)) return false
  const name = appDbContainer(slug)
  if ((await containerState(name)) !== 'running') return false
  const nets = await answersAsPostgres(name)
  if (nets.length === 0) return false
  console.log(`[app-db] ${name} answers to \`postgres\` on ${nets.join(', ')} — recreating it under its own name`)
  await retire(name)
  const password = readPasswordFile(envFile(slug))
  if (password) await spawnContainer(slug, password)
  return true
}

export type Occupant = { name: string; running: boolean }

/** Of `inspect -f '{{.Name}}\t{{.State.Running}}\t{{json .Mounts}}'` lines,
 *  the containers with a mount whose source is `dir`. Pure. */
export function occupantsOf(inspectLines: string, dir: string): Occupant[] {
  const want = resolve(dir)
  const out: Occupant[] = []
  for (const line of inspectLines.split('\n')) {
    const [rawName, running, json] = line.split('\t')
    if (!rawName || json === undefined) continue
    let mounts: unknown
    try {
      mounts = JSON.parse(json)
    } catch {
      continue
    }
    if (!Array.isArray(mounts)) continue
    const on = mounts.some((m) => {
      const src = (m as { Source?: unknown } | null)?.Source
      return typeof src === 'string' && resolve(src) === want
    })
    if (on) out.push({ name: rawName.replace(/^\//, ''), running: running === 'true' })
  }
  return out
}

/** What spawnContainer does about other app DB containers on this app's
 *  cluster directory, before it starts its own there. Two postmasters on one
 *  cluster corrupt it: in two containers neither sees the other's lock.
 *
 *  - In a devbox, `talaria-appdb-1-<slug>` is the box's own database from
 *    before the box's instance was its name (docker/devbox.compose.yml said
 *    `TALARIA_DEVBOX: '1'`). It runs on, `restart: unless-stopped`, while the
 *    app now asks for `talaria-appdb-<box>-<slug>`, and nothing else can be on
 *    this box's cluster under that name. It is retired, running or not.
 *  - Any other one that runs is refused: some other stack has this data
 *    directory (an inherited `TALARIA_APP_DATA_DIR`), and stopping its
 *    database is not this process's call.
 *  - A stopped one is left alone; it holds no lock to fight over. Pure. */
export function occupantPlan(
  occupants: Occupant[],
  devbox: string | undefined,
): { retire: string[]; refuse: string | null } {
  const ownOld = (o: Occupant) => Boolean(devbox) && devbox !== '1' && o.name.startsWith('talaria-appdb-1-')
  return {
    retire: occupants.filter(ownOld).map((o) => o.name),
    refuse: occupants.find((o) => o.running && !ownOld(o))?.name ?? null,
  }
}

/** Other app DB containers with this app's cluster directory mounted.
 *  Matched by mount source, so only a container on this very directory
 *  counts. A source this process cannot see as the daemon does (app data on a
 *  docker volume) matches nothing. */
async function occupants(slug: string, name: string): Promise<Occupant[]> {
  const ps = await docker(['ps', '-a', '--filter', 'name=^talaria-appdb-', '--format', '{{.Names}}'], 15_000)
  if (!ps.ok) return []
  const others = ps.stdout.split('\n').map((s) => s.trim()).filter((n) => n && n !== name)
  if (others.length === 0) return []
  const r = await docker(['inspect', '-f', '{{.Name}}\t{{.State.Running}}\t{{json .Mounts}}', ...others], 15_000)
  return r.ok ? occupantsOf(r.stdout, join(appDataDir(slug), 'pg')) : []
}

/** Stop a database cleanly (the postgres image stops on SIGINT, a fast
 *  shutdown), then remove the container. Its data is a bind mount, so it
 *  stays for the container that replaces it. */
async function retire(name: string): Promise<void> {
  await docker(['stop', '-t', '30', name], 60_000)
  await docker(['rm', '-f', name], 30_000)
}

async function publishedPort(name: string): Promise<number | null> {
  const r = await docker(['port', name, '5432/tcp'], 10_000)
  if (!r.ok) return null
  const m = r.stdout.match(/:(\d+)\s*$/)
  return m ? Number(m[1]) : null
}

async function spawnContainer(slug: string, password: string): Promise<void> {
  const name = appDbContainer(slug)
  const dir = appDataDir(slug)
  mkdirSync(join(dir, 'pg'), { recursive: true, mode: 0o700 })
  const plan = occupantPlan(await occupants(slug, name), process.env.TALARIA_DEVBOX)
  if (plan.refuse) {
    throw new Error(
      `app db ${slug}: ${plan.refuse} already runs on its data (${join(dir, 'pg')}), and two databases on one cluster corrupt it — stop that one first`,
    )
  }
  for (const old of plan.retire) {
    console.log(`[app-db] ${old} is this box's ${slug} database under its old name — stopping it before ${name} starts on the same data`)
    await retire(old)
  }
  writeDbEnv(slug, password)
  const network = await runningNetwork()
  writeFileSync(composeFile(slug), composeYaml({ image: await pinnedImage(), container: name, network }))
  let up = await compose(slug, ['up', '-d'], 180_000)
  if (!up.ok) {
    await docker(['rm', '-f', name], 30_000)
    up = await compose(slug, ['up', '-d'], 180_000)
  }
  if (!up.ok) throw new Error(`spawn app db ${slug}: ${up.stderr || up.stdout || 'docker compose up failed'}`)
  if (!network) await releaseLegacyNetwork(name)
}

export function appDbUrl(_slug: string, port: number | null, host: string, password: string): string {
  const pass = encodeURIComponent(password)
  const hostname = host.includes(':') ? `[${host}]` : host
  const p = port ?? 5432
  return `postgres://talaria:${pass}@${hostname}:${p}/talaria`
}


async function connectUrl(slug: string, password: string): Promise<string> {
  const name = appDbContainer(slug)
  if (dialsByName()) return appDbUrl(slug, 5432, name, password)
  const port = await publishedPort(name)
  if (port == null) throw new Error(`app db ${slug} has no published port`)
  return appDbUrl(slug, port, '127.0.0.1', password)
}

const SCHEMA = `
create table if not exists docs (
  collection text not null,
  id uuid not null default gen_random_uuid(),
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (collection, id)
);
create index if not exists docs_updated_idx on docs (collection, updated_at desc);
`

async function applyDump(slug: string): Promise<void> {
  const path = dumpFile(slug)
  if (!existsSync(path)) return
  const sql = readFileSync(path, 'utf8')
  const r = await docker(
    ['exec', '-i', appDbContainer(slug), 'psql', '-U', 'talaria', '-d', 'talaria', '-v', 'ON_ERROR_STOP=1', '-q'],
    180_000,
    sql,
  )
  if (!r.ok) throw new Error(`restore app db ${slug}: ${r.stderr || r.stdout || 'psql failed'}`)
  rmSync(path)
}

/** Spawn (if needed) and return a pooled client for this app's own Postgres. */
export async function appSql(slug: string): Promise<Sql> {
  if (!slugOk(slug)) throw new Error('bad slug')
  const hit = pools.get(slug)
  if (hit) return hit
  // First, before the password read below goes to the platform's database:
  // that read is one the alias can send to this app's database instead.
  await recreateIfAliased(slug)
  const password = await loadOrCreatePassword(slug)
  const name = appDbContainer(slug)
  const state = await containerState(name)
  if (state !== 'running') await spawnContainer(slug, password)
  if (!(await waitHealthy(name))) throw new Error(`app db ${slug} did not become ready`)
  await applyDump(slug)
  const sql = postgres(await connectUrl(slug, password), {
    max: 8,
    idle_timeout: 20,
    connect_timeout: 15,
    onnotice: () => {},
  })
  await sql.unsafe(SCHEMA)
  pools.set(slug, sql)
  return sql
}

/** Stop an app's database and close this process's pool for it. The data
 *  directory, db.env and the sealed password all stay: an app whose code left
 *  apps/ (uninstalled, or moved by hand) keeps its data until an admin asks
 *  for it to be wiped, which the api's uninstall does (talaria-apps
 *  `uninstall_app` with wipeData) — never this process. A reinstall reattaches
 *  the same cluster with the same password. */
export async function stopAppDatabase(slug: string): Promise<void> {
  if (!slugOk(slug)) return
  const sql = pools.get(slug)
  if (sql) {
    pools.delete(slug)
    try {
      await sql.end({ timeout: 2 })
    } catch {
      /* already gone */
    }
  }
  if (existsSync(composeFile(slug))) {
    await compose(slug, ['down', '--remove-orphans'], 60_000)
  }
  await docker(['rm', '-f', appDbContainer(slug)], 30_000)
}
